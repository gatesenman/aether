var codeRe = regexp.MustCompile(`^[EWMR][0-9]{3}$`)

func IsErrCode(s string) bool { return codeRe.MatchString(strings.ToUpper(s)) }

func ExplainCode(code string) (string, bool) {
	d, ok := ErrDocs[strings.ToUpper(code)]
	if !ok {
		return "", false
	}
	return fmt.Sprintf("%s  %s\n\n原因：%s\n修复：%s\n", d.Code, d.Title, d.Why, d.Fix), true
}

func ErrCodesSorted() []ErrDoc {
	ks := make([]string, 0, len(ErrDocs))
	for k := range ErrDocs {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	o := []ErrDoc{}
	for _, k := range ks {
		o = append(o, ErrDocs[k])
	}
	return o
}

// enrich adds the catalog title to a diagnostic (for --json / LSP consumers).
func enrichDiag(x Diag) Diag {
	if c, ok := x["code"].(string); ok {
		if d, ok := ErrDocs[c]; ok {
			x["title"] = d.Title
			x["explain"] = "aether explain " + c
		}
	}
	return x
}
